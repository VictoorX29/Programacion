    private void chkNegritaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_chkNegritaActionPerformed
        Font fuente = this.txtTexto.getFont();
        int estilo = fuente.getStyle(); // Capturamos el estilo de la fuente del txtTexto
        if(this.chkNegrita.isSelected()==true){
            estilo = estilo + Font.BOLD;
        }else{
            estilo = estilo - Font.BOLD;
        }
        // Actualizamos la fuente del txtTexto otra vez
        fuente = fuente.deriveFont(estilo);
        this.txtTexto.setFont(fuente);
    }//GEN-LAST:event_chkNegritaActionPerformed

    private void chkCursivaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_chkCursivaActionPerformed
        Font fuente = this.txtTexto.getFont();
        int estilo = fuente.getStyle();
        if(this.chkCursiva.isSelected()==true){
            estilo = estilo + Font.ITALIC;
        }else{
            estilo = estilo - Font.ITALIC;
        }
        fuente = fuente.deriveFont(estilo);
        this.txtTexto.setFont(fuente);
    }//GEN-LAST:event_chkCursivaActionPerformed

    private void cboColorFondoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cboColorFondoActionPerformed
        switch(this.cboColorFondo.getSelectedIndex()){
            case 0: // Rojo
                this.txtTexto.setBackground(Color.red);
                break;
            case 1: // Amarillo
                this.txtTexto.setBackground(Color.yellow);
                break;
            case 2: // Azul
                this.txtTexto.setBackground(Color.blue);
                break;
        }
    }//GEN-LAST:event_cboColorFondoActionPerformed

