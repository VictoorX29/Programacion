    private void lstTamañoValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstTamañoValueChanged
        Font fuente = this.txtTexto.getFont();
        float tamano = fuente.getSize();
        switch(this.lstTamaño.getSelectedIndex()){
            case 0: // tamaño 10
                tamano=10;
                break;
            case 1: // tamaño 20
                tamano=20;
                break;
            case 2: // tamaño 30
                tamano=30;
                break;
            case 3: // tamaño 40
                tamano=40;
                break;
        }
        fuente = fuente.deriveFont(tamano);
        this.txtTexto.setFont(fuente);
    }//GEN-LAST:event_lstTamañoValueChanged

